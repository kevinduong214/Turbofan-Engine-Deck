end


function normalizedMetric = normalize_masked_metric( ...
    rawMetric, activeMask)
%NORMALIZE_MASKED_METRIC Min-max normalize selected values to [0, 1].

normalizedMetric = nan(size(rawMetric));

activeValues = rawMetric(activeMask);

minimumValue = min(activeValues);
maximumValue = max(activeValues);
valueRange = maximumValue - minimumValue;

if valueRange <= eps(max(abs([minimumValue, maximumValue])))
    normalizedMetric(activeMask) = 0;
else
    normalizedMetric(activeMask) = ...
        (activeValues - minimumValue) ...
        / valueRange;
end

end


function save_study_figure( ...
    figHandle, figureFolder, baseName)
%SAVE_STUDY_FIGURE Apply styling and save PNG plus editable FIG.

apply_light_figure_style(figHandle);

pngPath = fullfile( ...
    figureFolder, ...
    baseName + ".png");

figPath = fullfile( ...
    figureFolder, ...
    baseName + ".fig");

exportgraphics( ...
    figHandle, ...
    pngPath, ...
    "Resolution", ...
    300, ...
    "BackgroundColor", ...
    "white");

savefig( ...
    figHandle, ...
    figPath);

end


function apply_light_figure_style(figHandle)
%APPLY_LIGHT_FIGURE_STYLE Force readable white figures with black text.

figHandle.Color = "w";

axesList = findall( ...
    figHandle, ...
    "Type", ...
    "axes");

for i = 1:numel(axesList)
    ax = axesList(i);

    ax.Color = "w";
    ax.XColor = "k";
    ax.YColor = "k";
    ax.GridColor = "k";
    ax.GridAlpha = 0.18;

    if isprop(ax, "MinorGridColor")
        ax.MinorGridColor = "k";
    end

    if isprop(ax, "MinorGridAlpha")
        ax.MinorGridAlpha = 0.10;
    end

    ax.Box = "on";

    if isprop(ax, "Toolbar")
        ax.Toolbar.Visible = "off";
    end
end

% Set only actual text objects to black. Do not assign the generic
% Color property on axes or legends, because for those objects Color
% controls the background rather than the text.
textList = findall( ...
    figHandle, ...
    "Type", ...
    "text");

for i = 1:numel(textList)
    textList(i).Color = "k";
end

legendList = findall( ...
    figHandle, ...
    "Type", ...
    "legend");

for i = 1:numel(legendList)
    lgd = legendList(i);

    if isprop(lgd, "TextColor")
        lgd.TextColor = "k";
    end

    if isprop(lgd, "Color")
        lgd.Color = "w";
    end

    if isprop(lgd, "EdgeColor")
        lgd.EdgeColor = "k";
    end
end

colorbarList = findall( ...
    figHandle, ...
    "Type", ...
    "ColorBar");

for i = 1:numel(colorbarList)
    cb = colorbarList(i);
    cb.Color = "k";
    cb.Label.Color = "k";

    if isprop(cb, "Title")
        cb.Title.Color = "k";
    end
end

end

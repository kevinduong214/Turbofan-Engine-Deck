        [baselineMarker, bestMarker], ...
        "Current baseline (fails Mach screen)", ...
        "Top-ranked candidate", ...
        "Location", "best");

    grid on;
    hold off;

    save_study_figure( ...
        fig, ...
        runOutput.figure_folder, ...
        "candidate_tradeoff_" + fileSuffix);

    %% Print ranking summary
    fprintf("Candidate-screening summary\n");
    fprintf("--------------------------------------------------\n");
    fprintf("Valid mean-line points:       %d of %d\n", ...
        numberValidPoints, ...
        numel(loadingGrid));
    fprintf("Feasible screened candidates: %d\n\n", ...
        numberFeasibleCandidates);

    fprintf("Ranking weights\n");
    fprintf("  Maximum Mach:               %.2f\n", ...
        weightMaximumMach);
    fprintf("  Radius deviation:           %.2f\n", ...
        weightRadiusDeviation);
    fprintf("  Exit span/radius:           %.2f\n", ...
        weightExitSpanRatio);
    fprintf("  Maximum flow angle:         %.2f\n\n", ...
        weightFlowAngle);

    fprintf("Baseline comparison\n");
    disp(baselineComparisonTable);

    fprintf("Top %d screened candidates\n", ...
        numberTopCandidates);

    disp(topCandidateTable(:, { ...
        'Rank', ...
        'LoadingCoefficient_psi', ...
        'FlowCoefficient_phi', ...
        'RankingScore', ...
        'MaximumMach', ...
        'MeanRadius_m', ...
        'ExitSpanToMeanRadius', ...
        'MaximumAbsoluteFlowAngle_deg'}));

    fprintf("The ranking is a transparent screening tool, not a\n");
    fprintf("claim that the first row is the final physical design.\n");
    fprintf("Do not update baseline_engine.m until the shortlist\n");
    fprintf("has been reviewed against the velocity triangles.\n\n");

    fprintf("Saved output files\n");
    fprintf("--------------------------------------------------\n");
    fprintf("Configuration:       %s\n", configurationPath);
    fprintf("Results MAT:         %s\n", resultsPath);
    fprintf("Full design CSV:     %s\n", designSpaceCsvPath);
    fprintf("Candidate CSV:       %s\n", candidateCsvPath);
    fprintf("Comparison CSV:      %s\n", comparisonCsvPath);
    fprintf("Command log:         %s\n", commandWindowPath);
    fprintf("==================================================\n");
    fprintf("HPT candidate-ranking study complete\n\n");

    diary off;

catch ME
    fprintf(2, ...
        "\nHPT candidate-ranking study failed.\n\n");

    fprintf(2, "%s\n", ...
        getReport( ...
            ME, ...
            "extended", ...
            "hyperlinks", ...
            "off"));

    diary off;
    rethrow(ME);
end


function normalizedMetric = normalize_feasible_metric( ...
    rawMetric, feasibleMask)
%NORMALIZE_FEASIBLE_METRIC Min-max normalize feasible values to [0, 1].

normalizedMetric = nan(size(rawMetric));

feasibleValues = rawMetric(feasibleMask);

minimumValue = min(feasibleValues);
maximumValue = max(feasibleValues);
valueRange = maximumValue - minimumValue;

if valueRange <= eps(max(abs([minimumValue, maximumValue])))
    normalizedMetric(feasibleMask) = 0;
else
    normalizedMetric(feasibleMask) = ...
        (feasibleValues - minimumValue) ...
        / valueRange;
end

end


function save_study_figure(figHandle, figureFolder, baseName)
%SAVE_STUDY_FIGURE Apply light styling and save PNG + FIG files.

apply_light_figure_style(figHandle);

pngPath = fullfile( ...
    figureFolder, ...
    baseName + ".png");

figPath = fullfile( ...
    figureFolder, ...
    baseName + ".fig");

exportgraphics( ...
    figHandle, ...
    pngPath, ...
    "Resolution", 300, ...
    "BackgroundColor", "white");

savefig( ...
    figHandle, ...
    char(figPath));

end


function apply_light_figure_style(figHandle)
%APPLY_LIGHT_FIGURE_STYLE Force white-background publication style.

figHandle.Color = "w";

axList = findall(figHandle, "Type", "axes");

for i = 1:numel(axList)
    ax = axList(i);

    ax.Color = "w";
    ax.XColor = "k";
    ax.YColor = "k";

    if isprop(ax, "ZColor")
        ax.ZColor = "k";
    end

    ax.Title.Color = "k";
    ax.XLabel.Color = "k";
    ax.YLabel.Color = "k";

    if isprop(ax, "YAxis") && numel(ax.YAxis) > 1
        for j = 1:numel(ax.YAxis)
            ax.YAxis(j).Color = "k";
        end
    end

    ax.GridColor = "k";
    ax.GridAlpha = 0.18;

    if isprop(ax, "MinorGridColor")
        ax.MinorGridColor = "k";
    end

    if isprop(ax, "MinorGridAlpha")
        ax.MinorGridAlpha = 0.10;
    end

    ax.Box = "on";

    if isprop(ax, "Toolbar")
        ax.Toolbar.Visible = "off";
    end
end

legendList = findall(figHandle, "Type", "legend");

for i = 1:numel(legendList)
    lgd = legendList(i);
    lgd.TextColor = "k";
    lgd.Color = "w";
    lgd.EdgeColor = [0.25 0.25 0.25];
end

textList = findall(figHandle, "Type", "text");

for i = 1:numel(textList)
    if isprop(textList(i), "Color")
        textList(i).Color = "k";
    end
end

colorbarList = findall(figHandle, "Type", "ColorBar");

for i = 1:numel(colorbarList)
    cb = colorbarList(i);
    cb.Color = "k";

    if isprop(cb, "Label")
        cb.Label.Color = "k";
    end

    if isprop(cb, "Title")
        cb.Title.Color = "k";
    end
end

end

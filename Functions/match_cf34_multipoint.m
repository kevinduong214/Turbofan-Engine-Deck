function solverOptions = apply_solver_option_overrides( ...
    solverOptions, ...
    diagnosticOptions)
%APPLY_SOLVER_OPTION_OVERRIDES Limit diagnostic solver budgets when requested.

allowedFields = [ ...
    "solver_max_iterations"
    "solver_max_function_evaluations"];

requestedFields = string(fieldnames(diagnosticOptions));

unexpectedFields = setdiff(requestedFields, allowedFields);

if ~isempty(unexpectedFields)
    error( ...
        "CF34Matcher:UnknownDiagnosticOption", ...
        "Unknown diagnostic option: %s", ...
        unexpectedFields(1));
end

if isfield(diagnosticOptions, "solver_max_iterations")
    validateattributes( ...
        diagnosticOptions.solver_max_iterations, ...
        {'numeric'}, ...
        {'scalar', 'real', 'finite', 'integer', 'nonnegative'});

    solverOptions.MaxIter = ...
        diagnosticOptions.solver_max_iterations;
end

if isfield(diagnosticOptions, "solver_max_function_evaluations")
    validateattributes( ...
        diagnosticOptions.solver_max_function_evaluations, ...
        {'numeric'}, ...
        {'scalar', 'real', 'finite', 'integer', 'positive'});

    solverOptions.MaxFunEvals = ...
        diagnosticOptions.solver_max_function_evaluations;
end

end


function [normalizedResiduals, rawResiduals, cfg, results] = ...
    evaluate_match(physical, pointCfg, logPressureRiseFractions)
%EVALUATE_MATCH Run one bounded effective operating state.

coreAirflow_kg_s = physical(1);
effectiveBypassRatio = physical(2);
effectiveOverallPressureRatio = physical(3);
combustorExitTemperature_K = physical(4);

componentPressureRatios = ...
    exp(logPressureRiseFractions * log(effectiveOverallPressureRatio));

cfg = pointCfg;
cfg.engine.core_airflow_kg_s = coreAirflow_kg_s;
cfg.engine.bypass_ratio = effectiveBypassRatio;
cfg.engine.target_overall_pressure_ratio = ...
    effectiveOverallPressureRatio;
cfg.engine.fan_pressure_ratio = componentPressureRatios(1);
cfg.engine.lpc_pressure_ratio = componentPressureRatios(2);
cfg.engine.hpc_pressure_ratio = componentPressureRatios(3);
cfg.engine.combustor_exit_temperature_K = ...
    combustorExitTemperature_K;
cfg.engine.turbine_inlet_temperature_K = ...
    combustorExitTemperature_K;

results = run_turbofan(cfg);

rawResiduals = [ ...
    results.performance.net_thrust_N ...
        - cfg.operating_point.target_thrust_N
    results.mass.mdot_fuel_kg_s ...
        - cfg.operating_point.target_fuel_flow_kg_s
    results.residuals.core_nozzle_capacity_kg_s
    results.residuals.bypass_nozzle_capacity_kg_s];

normalization = [ ...
    cfg.operating_point.target_thrust_N
    cfg.operating_point.target_fuel_flow_kg_s
    results.mass.mdot_hpt_kg_s
    results.mass.mdot_bypass_air_kg_s];

normalizedResiduals = rawResiduals ./ normalization;

end


function [jacobian, singularValues, jacobianRank, conditionNumber] = ...
    residual_jacobian( ...
        physical, ...
        pointCfg, ...
        logPressureRiseFractions, ...
        lowerBounds, ...
        upperBounds)
%RESIDUAL_JACOBIAN Diagnose local identifiability in scaled coordinates.

normalizedPhysical = ...
    (physical - lowerBounds) ...
    ./ (upperBounds - lowerBounds);

step = 1e-4;
jacobian = zeros(4);

for variableIndex = 1:4
    lowerCoordinate = normalizedPhysical;
    upperCoordinate = normalizedPhysical;

    lowerCoordinate(variableIndex) = max( ...
        1e-8, ...
        normalizedPhysical(variableIndex) - step);

    upperCoordinate(variableIndex) = min( ...
        1 - 1e-8, ...
        normalizedPhysical(variableIndex) + step);

    lowerPhysical = ...
        lowerBounds ...
        + lowerCoordinate .* (upperBounds - lowerBounds);

    upperPhysical = ...
        lowerBounds ...
        + upperCoordinate .* (upperBounds - lowerBounds);

    lowerResidual = evaluate_match( ...
        lowerPhysical, ...
        pointCfg, ...
        logPressureRiseFractions);

    upperResidual = evaluate_match( ...
        upperPhysical, ...
        pointCfg, ...
        logPressureRiseFractions);

    coordinateDifference = ...
        upperCoordinate(variableIndex) ...
        - lowerCoordinate(variableIndex);

    jacobian(:, variableIndex) = ...
        (upperResidual - lowerResidual) ...
        / coordinateDifference;
end

singularValues = svd(jacobian);
jacobianRank = rank(jacobian);

if singularValues(end) <= eps(singularValues(1))
    conditionNumber = Inf;
else
    conditionNumber = singularValues(1) / singularValues(end);
end

end

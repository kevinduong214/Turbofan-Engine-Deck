        'Classification', ...
        'FeasibilityStatus', ...
        'ActiveBounds', ...
        'TargetProvenance', ...
        'TargetThrustBasis'});

match = struct();
match.method = ...
    "reduced-order, steady-state, fixed-nozzle-area multipoint matcher";
match.scope = ...
    "Three diagnostic EDB feasibility targets; APR preserved; idle, maximum-continuous, and cruise remain holdouts";
match.classification = ...
    "diagnostic_feasibility_study";
match.is_accepted_off_design_model = false;
match.exact_solution_tolerance = exactSolutionTolerance;
match.effective_quantity_names = [ ...
    "CoreAirflow_kg_s" ...
    "EffectiveBypassRatio" ...
    "EffectiveOverallPressureRatio" ...
    "CombustorExitTemperature_K"];
match.residual_names = [ ...
    "Thrust_N" ...
    "FuelFlow_kg_s" ...
    "CoreNozzleCapacity_kg_s" ...
    "BypassNozzleCapacity_kg_s"];
match.lower_bounds = lowerBounds;
match.upper_bounds = upperBounds;
match.solver_options = solverOptions;
match.deterministic_start_count = size(physicalStarts, 1);
match.solver_failure_status = ...
    "solver_failure_no_successful_start";
match.log_pressure_rise_fractions = logPressureRiseFractions;
match.apr.cfg = aprCfg;
match.apr.results = aprResults;
match.cases = cases;
match.schedule = schedule;
match.limitations = [ ...
    "No EDB point is an accepted calibrated operating point or validated prediction."
    "Failure to find an exact solution with this bounded multistart local diagnostic is not a global proof that no exact root exists."
    "Public APR BPR/OPR values and UID 10GE133 EDB values have mixed pedigree and are not proven to describe identical internal engine states."
    "Climb-out and approach thrust targets are derived from percent Foo rather than independent net-thrust measurements at the modeled ambient midpoint."
    "The effective bypass ratio is a modeled mass-flow ratio, not a geometry change."
    "No compressor maps, turbine maps, spool-speed matching, or proprietary control schedule are represented."];


    function recordedObjective = recorded_objective(unconstrained)
    %RECORDED_OBJECTIVE Evaluate and retain expected domain failures.

        [recordedObjective, failure] = objective_value( ...
            unconstrained, ...
            pointCfg, ...
            logPressureRiseFractions, ...
            lowerBounds, ...
            upperBounds);

        if failure.occurred
            record_expected_failure( ...
                failure, ...
                unconstrained, ...
                "solver objective evaluation");
        end
    end


    function record_expected_failure(failure, unconstrained, phase)
    %RECORD_EXPECTED_FAILURE Retain source and state for diagnosis.

        physical = from_unconstrained( ...
            unconstrained, ...
            lowerBounds, ...
            upperBounds);

        context = sprintf( ...
            "point=%s; start=%d; phase=%s; physical=%s", ...
            currentPointId, ...
            currentStartIndex, ...
            phase, ...
            mat2str(physical, 10));

        currentExpectedFailureIdentifiers(end + 1, 1) = ...
            failure.identifier;
        currentExpectedFailureMessages(end + 1, 1) = ...
            failure.message;
        currentExpectedFailureContexts(end + 1, 1) = ...
            context;
    end

end


function label = active_bound_labels(physical, lowerBounds, upperBounds)
%ACTIVE_BOUND_LABELS Report bounds active at a constrained diagnostic result.

variableNames = [ ...
    "core_airflow" ...
    "effective_bypass_ratio" ...
    "effective_overall_pressure_ratio" ...
    "combustor_exit_temperature"];

activeLabels = strings(0, 1);
boundTolerance = 1e-8 * (upperBounds - lowerBounds);

for variableIndex = 1:numel(physical)
    if physical(variableIndex) - lowerBounds(variableIndex) ...
            <= boundTolerance(variableIndex)
        activeLabels(end + 1, 1) = ...
            variableNames(variableIndex) + "_lower";
    end

    if upperBounds(variableIndex) - physical(variableIndex) ...
            <= boundTolerance(variableIndex)
        activeLabels(end + 1, 1) = ...
            variableNames(variableIndex) + "_upper";
    end
end

if isempty(activeLabels)
    label = "none";
else
    label = strjoin(activeLabels, ", ");
end

end


function physical = initial_guess( ...
    cfgApr, ...
    designOverallPressureRatio, ...
    powerFraction, ...
    lowerBounds, ...
    upperBounds)
%INITIAL_GUESS Build one deterministic physics-scaled starting point.

coreAirflow = ...
    cfgApr.engine.core_airflow_kg_s ...
    * (0.12 + 0.88 * powerFraction);

effectiveBypassRatio = ...
    cfgApr.engine.bypass_ratio;

effectiveOverallPressureRatio = ...
    1 + (designOverallPressureRatio - 1) ...
    * powerFraction^0.70;

combustorExitTemperature = ...
    550 + (cfgApr.engine.combustor_exit_temperature_K - 550) ...
    * powerFraction^0.30;

physical = [ ...
    coreAirflow, ...
    effectiveBypassRatio, ...
    effectiveOverallPressureRatio, ...
    combustorExitTemperature];

physical = clip_inside_bounds( ...
    physical, ...
    lowerBounds, ...
    upperBounds);

end


function starts = deterministic_starts(initial, lowerBounds, upperBounds)
%DETERMINISTIC_STARTS Provide repeatable alternatives for the local solver.

relativeOffsets = [ ...
     0.00,  0.00,  0.00,  0.00
    -0.12,  0.08, -0.12, -0.08
     0.12, -0.08,  0.12,  0.08
    -0.08, -0.08,  0.10, -0.12
     0.08,  0.08, -0.10,  0.12];

range = upperBounds - lowerBounds;
starts = initial + relativeOffsets .* range;

for startIndex = 1:size(starts, 1)
    starts(startIndex, :) = clip_inside_bounds( ...
        starts(startIndex, :), ...
        lowerBounds, ...
        upperBounds);
end

end


function clipped = clip_inside_bounds(values, lowerBounds, upperBounds)
%CLIP_INSIDE_BOUNDS Keep starts away from asymptotic transformed bounds.

margin = 1e-5 * (upperBounds - lowerBounds);
clipped = min(max(values, lowerBounds + margin), upperBounds - margin);

end


function unconstrained = to_unconstrained(physical, lowerBounds, upperBounds)
%TO_UNCONSTRAINED Apply a bounded logistic coordinate transform.

fraction = ...
    (physical - lowerBounds) ...
    ./ (upperBounds - lowerBounds);

fraction = min(max(fraction, 1e-10), 1 - 1e-10);
unconstrained = log(fraction ./ (1 - fraction));

end


function physical = from_unconstrained(unconstrained, lowerBounds, upperBounds)
%FROM_UNCONSTRAINED Recover bounded effective operating quantities.

fraction = 1 ./ (1 + exp(-unconstrained));
physical = lowerBounds + fraction .* (upperBounds - lowerBounds);

end


function [objective, failure] = objective_value( ...
    unconstrained, ...
    pointCfg, ...
    logPressureRiseFractions, ...
    lowerBounds, ...
    upperBounds)
%OBJECTIVE_VALUE Return the squared normalized four-residual norm.

failure = struct( ...
    'occurred', false, ...
    'identifier', "", ...
    'message', "");

physical = from_unconstrained( ...
    unconstrained, ...
    lowerBounds, ...
    upperBounds);

try
    normalizedResiduals = evaluate_match( ...
        physical, ...
        pointCfg, ...
        logPressureRiseFractions);

    if any(~isfinite(normalizedResiduals))
        failure.occurred = true;
        failure.identifier = ...
            "CF34Matcher:NonfiniteModelDomainEvaluation";
        failure.message = ...
            "Cycle evaluator returned a nonfinite normalized residual.";
        objective = domain_failure_penalty(unconstrained);
    else
        objective = sum(normalizedResiduals .^ 2);
    end
catch exception
    if ~is_expected_model_domain_error(exception)
        rethrow(exception)
    end

    failure.occurred = true;
    failure.identifier = string(exception.identifier);

    if strlength(failure.identifier) == 0
        failure.identifier = ...
            "CF34Matcher:ExpectedModelDomainFailure";
    end

    failure.message = string(exception.message);
    objective = domain_failure_penalty(unconstrained);
end

end


function penalty = domain_failure_penalty(unconstrained)
%DOMAIN_FAILURE_PENALTY Keep expected inadmissible states out of the fit.

boundedCoordinate = min(abs(unconstrained), 1e6);
penalty = 1e12 + sum(boundedCoordinate .^ 2);

end


function expected = is_expected_model_domain_error(exception)
%IS_EXPECTED_MODEL_DOMAIN_ERROR Whitelist physical-domain evaluation errors.

expectedMessages = [ ...
    "Invalid combustor energy balance: denominator is nonpositive."
    "Calculated fuel-air ratio is nonpositive."

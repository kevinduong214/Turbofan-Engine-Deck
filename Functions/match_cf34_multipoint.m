function match = match_cf34_multipoint(cfgApr, diagnosticOptions)
%MATCH_CF34_MULTIPOINT Diagnose three public CF34-10E feasibility targets.
% This reduced-order, steady-state, fixed-nozzle-area matcher preserves the
% Automatic Power Reserve (APR) design point and diagnoses normal takeoff,
% climb-out, and approach targets from the ICAO Engine Emissions Databank
% (EDB). It is not an accepted off-design model or control schedule.
% Effective core flow, bypass ratio, overall pressure ratio, and combustor
% exit temperature minimize thrust, fuel-flow, and nozzle-capacity residuals.
% APR logarithmic pressure-rise fractions define the component split.
% Bounded deterministic local searches do not prove global infeasibility.
% diagnosticOptions may change solver budgets only.

validateattributes(cfgApr, {'struct'}, {'scalar'});

if nargin < 2
    diagnosticOptions = struct();
end

validateattributes(diagnosticOptions, {'struct'}, {'scalar'});

requiredGeometryFields = [ ...
    "core_nozzle_area_m2", ...
    "bypass_nozzle_area_m2"];

for fieldIndex = 1:numel(requiredGeometryFields)
    if ~isfield(cfgApr.geometry, requiredGeometryFields(fieldIndex))
        error( ...
            "Missing fixed-nozzle geometry field: %s", ...
            requiredGeometryFields(fieldIndex));
    end
end

%% Preserve and evaluate the inherited APR baseline
aprCfg = cfgApr;
aprResults = run_turbofan(aprCfg);

designComponentPressureRatios = [ ...
    aprCfg.engine.fan_pressure_ratio, ...
    aprCfg.engine.lpc_pressure_ratio, ...
    aprCfg.engine.hpc_pressure_ratio];

designOverallPressureRatio = ...
    prod(designComponentPressureRatios);

logPressureRiseFractions = ...
    log(designComponentPressureRatios) ...
    / log(designOverallPressureRatio);

%% Supported EDB diagnostic feasibility points
pointIds = [ ...
    "normal_takeoff_edb" ...
    "climb_out_edb" ...
    "approach_edb"];

numberPoints = numel(pointIds);

exactSolutionTolerance = 5e-5;

% Bounds apply only to EDB diagnostics; APR is not optimized.
lowerBounds = [ ...
    5.0, ...       % core airflow, kg/s
    2.0, ...       % effective bypass ratio
    2.0, ...       % effective overall pressure ratio
    700.0];        % combustor exit temperature, K

upperBounds = [ ...
    aprCfg.engine.core_airflow_kg_s, ...
    8.0, ...
    designOverallPressureRatio, ...
    aprCfg.engine.combustor_exit_temperature_K];

solverOptions = optimset( ...
    'Display', 'off', ...
    'MaxFunEvals', 6000, ...
    'MaxIter', 2500, ...
    'TolFun', 1e-14, ...
    'TolX', 1e-10);

solverOptions = apply_solver_option_overrides( ...
    solverOptions, ...
    diagnosticOptions);

startTemplate = struct( ...
    'start_index', NaN, ...
    'initial_physical', nan(1, 4), ...
    'terminal_physical', nan(1, 4), ...
    'objective', NaN, ...
    'recomputed_objective', NaN, ...
    'objective_consistency_error', NaN, ...
    'exit_flag', NaN, ...
    'iterations', NaN, ...
    'function_evaluations', NaN, ...
    'solver_exit_success', false, ...
    'terminal_evaluation_valid', false, ...
    'objective_consistent', false, ...
    'selected', false, ...
    'expected_failure_count', 0, ...
    'expected_failure_identifiers', strings(0, 1), ...
    'expected_failure_messages', strings(0, 1), ...
    'expected_failure_contexts', strings(0, 1));

caseTemplate = struct( ...
    'point_id', "", ...
    'classification', "diagnostic", ...
    'feasibility_status', "", ...
    'is_exact_solution', false, ...
    'active_bounds', "none", ...
    'target_provenance', "", ...
    'target_thrust_basis', "", ...
    'solver_success', false, ...
    'selected_start_index', NaN, ...
    'start_diagnostics', repmat(startTemplate, 0, 1), ...
    'expected_domain_failure_count', 0, ...
    'unexpected_exception_count', 0, ...
    'cfg', struct(), ...
    'results', struct(), ...
    'raw_residuals', zeros(4, 1), ...
    'normalized_residuals', zeros(4, 1), ...
    'objective', NaN, ...
    'recomputed_objective', NaN, ...
    'objective_consistency_error', NaN, ...
    'exit_flag', NaN, ...
    'iterations', NaN, ...
    'function_evaluations', NaN, ...
    'jacobian', nan(4), ...
    'jacobian_singular_values', nan(4, 1), ...
    'jacobian_rank', NaN, ...
    'jacobian_condition_number', NaN);

cases = repmat(caseTemplate, numberPoints, 1);

currentPointId = "";
currentStartIndex = NaN;
currentExpectedFailureIdentifiers = strings(0, 1);
currentExpectedFailureMessages = strings(0, 1);
currentExpectedFailureContexts = strings(0, 1);

for pointIndex = 1:numberPoints
    pointCfg = apply_cf34_operating_point( ...
        aprCfg, ...
        pointIds(pointIndex));

    powerFraction = ...
        pointCfg.operating_point.target_thrust_N ...
        / aprCfg.operating_point.target_thrust_N;

    initialPhysical = initial_guess( ...
        aprCfg, ...
        designOverallPressureRatio, ...
        powerFraction, ...
        lowerBounds, ...
        upperBounds);

    physicalStarts = deterministic_starts( ...
        initialPhysical, ...
        lowerBounds, ...
        upperBounds);

    startDiagnostics = repmat( ...
        startTemplate, ...
        size(physicalStarts, 1), ...
        1);

    bestObjective = Inf;
    bestState = [];
    bestExitFlag = NaN;
    bestOutput = struct();
    bestStartIndex = NaN;

    currentPointId = pointIds(pointIndex);

    for startIndex = 1:size(physicalStarts, 1)
        currentStartIndex = startIndex;
        currentExpectedFailureIdentifiers = strings(0, 1);
        currentExpectedFailureMessages = strings(0, 1);
        currentExpectedFailureContexts = strings(0, 1);

        initialUnconstrained = to_unconstrained( ...
            physicalStarts(startIndex, :), ...
            lowerBounds, ...
            upperBounds);

        objectiveFunction = @recorded_objective;

        [candidateState, candidateObjective, candidateExitFlag, candidateOutput] = ...
            fminsearch( ...
                objectiveFunction, ...
                initialUnconstrained, ...
                solverOptions);

        candidatePhysical = from_unconstrained( ...
            candidateState, ...
            lowerBounds, ...
            upperBounds);

        [candidateRecomputedObjective, terminalFailure] = ...
            objective_value( ...
                candidateState, ...
                pointCfg, ...
                logPressureRiseFractions, ...
                lowerBounds, ...
                upperBounds);

        if terminalFailure.occurred
            record_expected_failure( ...
                terminalFailure, ...
                candidateState, ...
                "terminal evaluation");
        end

        objectiveConsistencyError = abs( ...
            candidateObjective - candidateRecomputedObjective);

        objectiveConsistencyTolerance = ...
            1e-12 * max(1, abs(candidateRecomputedObjective));

        terminalEvaluationValid = ...
            ~terminalFailure.occurred ...
            && isfinite(candidateRecomputedObjective);

        objectiveConsistent = ...
            terminalEvaluationValid ...
            && objectiveConsistencyError ...
                <= objectiveConsistencyTolerance;

        solverExitSuccess = ...
            candidateExitFlag > 0;

        candidateSucceeded = ...
            solverExitSuccess ...
            && terminalEvaluationValid ...
            && objectiveConsistent;

        startDiagnostics(startIndex).start_index = startIndex;
        startDiagnostics(startIndex).initial_physical = ...
            physicalStarts(startIndex, :);
        startDiagnostics(startIndex).terminal_physical = ...
            candidatePhysical;
        startDiagnostics(startIndex).objective = ...
            candidateObjective;
        startDiagnostics(startIndex).recomputed_objective = ...
            candidateRecomputedObjective;
        startDiagnostics(startIndex).objective_consistency_error = ...
            objectiveConsistencyError;
        startDiagnostics(startIndex).exit_flag = ...
            candidateExitFlag;
        startDiagnostics(startIndex).iterations = ...
            candidateOutput.iterations;
        startDiagnostics(startIndex).function_evaluations = ...
            candidateOutput.funcCount;
        startDiagnostics(startIndex).solver_exit_success = ...
            solverExitSuccess;
        startDiagnostics(startIndex).terminal_evaluation_valid = ...
            terminalEvaluationValid;
        startDiagnostics(startIndex).objective_consistent = ...
            objectiveConsistent;
        startDiagnostics(startIndex).expected_failure_count = ...
            numel(currentExpectedFailureIdentifiers);
        startDiagnostics(startIndex).expected_failure_identifiers = ...
            currentExpectedFailureIdentifiers;
        startDiagnostics(startIndex).expected_failure_messages = ...
            currentExpectedFailureMessages;
        startDiagnostics(startIndex).expected_failure_contexts = ...
            currentExpectedFailureContexts;

        if candidateSucceeded ...
                && candidateRecomputedObjective < bestObjective
            bestObjective = candidateRecomputedObjective;
            bestState = candidateState;
            bestExitFlag = candidateExitFlag;
            bestOutput = candidateOutput;
            bestStartIndex = startIndex;
        end
    end

    totalExpectedFailureCount = ...
        sum([startDiagnostics.expected_failure_count]);

    if isnan(bestStartIndex)
        cases(pointIndex).point_id = pointIds(pointIndex);
        cases(pointIndex).classification = "diagnostic";
        cases(pointIndex).feasibility_status = ...
            "solver_failure_no_successful_start";
        cases(pointIndex).solver_success = false;
        cases(pointIndex).start_diagnostics = startDiagnostics;
        cases(pointIndex).expected_domain_failure_count = ...
            totalExpectedFailureCount;
        cases(pointIndex).target_provenance = ...
            pointCfg.operating_point.source;
        cases(pointIndex).target_thrust_basis = ...
            pointCfg.operating_point.target_thrust_basis;
        cases(pointIndex).cfg = pointCfg;
        continue
    end

    startDiagnostics(bestStartIndex).selected = true;

    bestPhysical = from_unconstrained( ...
        bestState, ...
        lowerBounds, ...
        upperBounds);

    [normalizedResiduals, rawResiduals, matchedCfg, matchedResults] = ...
        evaluate_match( ...
            bestPhysical, ...
            pointCfg, ...
            logPressureRiseFractions);

    recomputedObjective = ...
        sum(normalizedResiduals .^ 2);

    objectiveConsistencyError = ...
        abs(bestObjective - recomputedObjective);

    objectiveConsistencyTolerance = ...
        1e-12 * max(1, abs(recomputedObjective));

    if objectiveConsistencyError > objectiveConsistencyTolerance
        error( ...
            "CF34Matcher:SelectedObjectiveMismatch", ...
            "Selected objective is inconsistent with its normalized residuals.");
    end

    [jacobian, singularValues, jacobianRank, conditionNumber] = ...
        residual_jacobian( ...
            bestPhysical, ...
            pointCfg, ...
            logPressureRiseFractions, ...
            lowerBounds, ...
            upperBounds);

    activeBounds = active_bound_labels( ...
        bestPhysical, ...
        lowerBounds, ...
        upperBounds);

    isExactSolution = ...
        max(abs(normalizedResiduals)) <= exactSolutionTolerance;

    if isExactSolution
        feasibilityStatus = "exact_solution_found_within_bounds";
    else
        feasibilityStatus = "no_exact_solution_found_within_bounds";
    end

    cases(pointIndex).point_id = pointIds(pointIndex);
    cases(pointIndex).classification = "diagnostic";
    cases(pointIndex).feasibility_status = feasibilityStatus;
    cases(pointIndex).is_exact_solution = isExactSolution;
    cases(pointIndex).active_bounds = activeBounds;
    cases(pointIndex).target_provenance = pointCfg.operating_point.source;
    cases(pointIndex).target_thrust_basis = ...
        pointCfg.operating_point.target_thrust_basis;
    cases(pointIndex).solver_success = true;
    cases(pointIndex).selected_start_index = bestStartIndex;
    cases(pointIndex).start_diagnostics = startDiagnostics;
    cases(pointIndex).expected_domain_failure_count = ...
        totalExpectedFailureCount;
    cases(pointIndex).cfg = matchedCfg;
    cases(pointIndex).results = matchedResults;
    cases(pointIndex).raw_residuals = rawResiduals;
    cases(pointIndex).normalized_residuals = normalizedResiduals;
    cases(pointIndex).objective = bestObjective;
    cases(pointIndex).recomputed_objective = recomputedObjective;
    cases(pointIndex).objective_consistency_error = ...
        objectiveConsistencyError;
    cases(pointIndex).exit_flag = bestExitFlag;
    cases(pointIndex).iterations = bestOutput.iterations;
    cases(pointIndex).function_evaluations = bestOutput.funcCount;
    cases(pointIndex).jacobian = jacobian;
    cases(pointIndex).jacobian_singular_values = singularValues;
    cases(pointIndex).jacobian_rank = jacobianRank;
    cases(pointIndex).jacobian_condition_number = conditionNumber;
end

%% Assemble effective schedule and diagnostics
powerSetting_percentFoo = nan(numberPoints, 1);
coreAirflow_kg_s = nan(numberPoints, 1);
effectiveBypassRatio = nan(numberPoints, 1);
fanPressureRatio = nan(numberPoints, 1);
lpcPressureRatio = nan(numberPoints, 1);
hpcPressureRatio = nan(numberPoints, 1);
effectiveOverallPressureRatio = nan(numberPoints, 1);
combustorExitTemperature_K = nan(numberPoints, 1);
thrustResidual_N = nan(numberPoints, 1);
fuelFlowResidual_kg_s = nan(numberPoints, 1);
coreNozzleCapacityResidual_kg_s = nan(numberPoints, 1);
bypassNozzleCapacityResidual_kg_s = nan(numberPoints, 1);
maximumNormalizedResidual = nan(numberPoints, 1);
jacobianConditionNumber = nan(numberPoints, 1);
solverSuccess = false(numberPoints, 1);
selectedExitFlag = nan(numberPoints, 1);
selectedStartIndex = nan(numberPoints, 1);
objective = nan(numberPoints, 1);
objectiveConsistencyError = nan(numberPoints, 1);
expectedDomainFailureCount = zeros(numberPoints, 1);
classification = repmat("diagnostic", numberPoints, 1);
feasibilityStatus = strings(numberPoints, 1);
activeBounds = strings(numberPoints, 1);
targetProvenance = strings(numberPoints, 1);
targetThrustBasis = strings(numberPoints, 1);

for pointIndex = 1:numberPoints
    pointCfg = cases(pointIndex).cfg;

    powerSetting_percentFoo(pointIndex) = ...
        pointCfg.operating_point.power_setting_percent_Foo;

    if cases(pointIndex).solver_success
        coreAirflow_kg_s(pointIndex) = ...
            pointCfg.engine.core_airflow_kg_s;

        effectiveBypassRatio(pointIndex) = ...
            pointCfg.engine.bypass_ratio;

        fanPressureRatio(pointIndex) = ...
            pointCfg.engine.fan_pressure_ratio;

        lpcPressureRatio(pointIndex) = ...
            pointCfg.engine.lpc_pressure_ratio;

        hpcPressureRatio(pointIndex) = ...
            pointCfg.engine.hpc_pressure_ratio;

        effectiveOverallPressureRatio(pointIndex) = ...
            fanPressureRatio(pointIndex) ...
            * lpcPressureRatio(pointIndex) ...
            * hpcPressureRatio(pointIndex);

        combustorExitTemperature_K(pointIndex) = ...
            pointCfg.engine.combustor_exit_temperature_K;

        thrustResidual_N(pointIndex) = ...
            cases(pointIndex).raw_residuals(1);

        fuelFlowResidual_kg_s(pointIndex) = ...
            cases(pointIndex).raw_residuals(2);

        coreNozzleCapacityResidual_kg_s(pointIndex) = ...
            cases(pointIndex).raw_residuals(3);

        bypassNozzleCapacityResidual_kg_s(pointIndex) = ...
            cases(pointIndex).raw_residuals(4);

        maximumNormalizedResidual(pointIndex) = ...
            max(abs(cases(pointIndex).normalized_residuals));

        jacobianConditionNumber(pointIndex) = ...
            cases(pointIndex).jacobian_condition_number;
    end

    solverSuccess(pointIndex) = ...
        cases(pointIndex).solver_success;

    selectedExitFlag(pointIndex) = ...
        cases(pointIndex).exit_flag;

    selectedStartIndex(pointIndex) = ...
        cases(pointIndex).selected_start_index;

    objective(pointIndex) = ...
        cases(pointIndex).objective;

    objectiveConsistencyError(pointIndex) = ...
        cases(pointIndex).objective_consistency_error;

    expectedDomainFailureCount(pointIndex) = ...
        cases(pointIndex).expected_domain_failure_count;

    feasibilityStatus(pointIndex) = ...
        cases(pointIndex).feasibility_status;

    activeBounds(pointIndex) = ...
        cases(pointIndex).active_bounds;

    targetProvenance(pointIndex) = ...
        cases(pointIndex).target_provenance;

    targetThrustBasis(pointIndex) = ...
        cases(pointIndex).target_thrust_basis;
end

schedule = table( ...
    pointIds', ...
    powerSetting_percentFoo, ...
    coreAirflow_kg_s, ...
    effectiveBypassRatio, ...
    fanPressureRatio, ...
    lpcPressureRatio, ...
    hpcPressureRatio, ...
    effectiveOverallPressureRatio, ...
    combustorExitTemperature_K, ...
    thrustResidual_N, ...
    fuelFlowResidual_kg_s, ...
    coreNozzleCapacityResidual_kg_s, ...
    bypassNozzleCapacityResidual_kg_s, ...
    maximumNormalizedResidual, ...
    jacobianConditionNumber, ...
    solverSuccess, ...
    selectedExitFlag, ...
    selectedStartIndex, ...
    objective, ...
    objectiveConsistencyError, ...
    expectedDomainFailureCount, ...
    classification, ...
    feasibilityStatus, ...
    activeBounds, ...
    targetProvenance, ...
    targetThrustBasis, ...
    'VariableNames', { ...
        'PointId', ...
        'PowerSetting_percentFoo', ...
        'CoreAirflow_kg_s', ...
        'EffectiveBypassRatio', ...
        'FanPressureRatio', ...
        'LPCPressureRatio', ...
        'HPCPressureRatio', ...
        'EffectiveOverallPressureRatio', ...
        'CombustorExitTemperature_K', ...
        'ThrustResidual_N', ...
        'FuelFlowResidual_kg_s', ...
        'CoreNozzleCapacityResidual_kg_s', ...
        'BypassNozzleCapacityResidual_kg_s', ...
        'MaximumNormalizedResidual', ...
